namespace Kaizen.BlogEngine;

public sealed class CollectionOptions
{
    /// <summary>Collection name used to look it up in <see cref="ContentCatalog"/>, e.g. "blog" or "pages".</summary>
    public string Name { get; set; } = "blog";
    /// <summary>Folder of *.md files; relative paths resolve against the content root.</summary>
    public string ContentPath { get; set; } = "content/posts";
    /// <summary>URL prefix used to build <see cref="ContentPage.Url"/>: "/blog" gives /blog/{slug}/, "" gives /{slug}/.</summary>
    public string UrlPrefix { get; set; } = "/blog";
    /// <summary>Drafts are hidden unless this is true (e.g. in a dev server).</summary>
    public bool IncludeDrafts { get; set; }
    /// <summary>The collection has a date-sorted index page at its prefix (e.g. /blog/). Plain pages: false.</summary>
    public bool Index { get; set; }
    /// <summary>The collection publishes a feed. Declared for sites to read; no feed is generated by the library yet.</summary>
    public bool Feed { get; set; }
    /// <summary>Tags are meaningful for this collection (tag listings / hub filtering).</summary>
    public bool Tags { get; set; }
}
